/* Frame FSK — 14 bytes, 112 bits MSB-first
 *
 * Layout derived from observed Civicex captures:
 *   byte  0      : hdr(4) | btn(4)
 *   bytes 1..2   : serial high 16 bit
 *   byte  3 hi   : serial low 4 bit           → serial = 20 bit total
 *   byte  3 lo   : flags / retrans-toggle 4 bit
 *   bytes 4..7   : static device fingerprint 32 bit
 *   byte  8      : rolling checksum (XOR over bytes 0..7 in our roundtrip)
 *   byte  9      : status / reserved (observed 0x00)
 *   bytes 10..11 : 16-bit rolling counter (monotonic across retransmits)
 *   bytes 12..13 : 16-bit tail (CRC / cipher output)
 */
typedef struct {
    uint8_t  hdr;           /* 4 bit */
    uint8_t  button;        /* 4 bit */
    uint32_t serial;        /* 20 bit */
    uint8_t  flags;         /* 4 bit (byte 3 low nibble) */
    uint32_t fingerprint;   /* 32 bit (bytes 4..7) */
    uint8_t  checksum;      /* byte 8 */
    uint8_t  status;        /* byte 9 */
    uint16_t counter;       /* bytes 10..11 */
    uint16_t tail;          /* bytes 12..13 */
} HondaV9Frame;

