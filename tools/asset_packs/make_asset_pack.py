#!/usr/bin/env python3
"""
make_asset_pack.py -- build a Momentum-flavor asset pack (a "theme") for the
applab ESP32 Flipper ports (Cardputer ADV / M5Stick S3 / LilyGo T-Embed CC1101).

An asset pack lets you replace the firmware's built-in ICONS and FONTS with your
own, loaded from the microSD at runtime. Drop the built pack in:

    /asset_packs/<PackName>/           (root of a FAT32 microSD)

then pick it on the device under  Settings -> Desktop -> Asset Pack.

--------------------------------------------------------------------------------
INPUT LAYOUT  (a folder of PNGs mirroring the pack)
--------------------------------------------------------------------------------
    <input>/
      Icons/
        Battery_26x8.png              -> static icon  (one PNG)
        WarningDolphinFlip_45x42/     -> animated icon (a folder of frames)
          frame_00.png
          frame_01.png
          meta.txt                    -> optional, one line: "frame_rate=2"
      Fonts/
        Primary.u8f                   -> optional, copied through as-is

  * The file/folder name (minus .png) is the ICON NAME to replace. It MUST match
    a name from ASSET_PACK_ICONS.txt (generated by gen_icon_manifest.py). The
    trailing "_WxH" is only a human hint; the real size comes from the PNG.
  * A pixel is "on" (drawn in the UI foreground colour) when it is dark
    (luminance < 128) and not transparent. White/transparent = background.
  * Font files must already be in u8g2 .u8f format; this tool only copies them.
    Valid slot names: Primary, Secondary, Keyboard, BigNumbers, BatteryPercent.

--------------------------------------------------------------------------------
OUTPUT (the on-SD format the firmware's asset_packs.c reads)
--------------------------------------------------------------------------------
    <output>/<PackName>/
      Icons/<name>.bmx                          static:  int32 w,h + frame blob
      Icons/<name>/meta                         animated: int32 w,h,rate,count
      Icons/<name>/frame_00.bm ...              animated: one frame blob each
      Fonts/<Slot>.u8f

  A "frame blob" is  b"\\x00" + XBM(1bpp, LSB-first, rows byte-padded)  --
  the uncompressed icon encoding the firmware decodes via compress_icon_decode().

Usage:
    python make_asset_pack.py <input_dir> <PackName> [--out OUTDIR] [--rate N]
"""

import argparse
import struct
import sys
from pathlib import Path

try:
    from PIL import Image
except ImportError:
    sys.exit("This tool needs Pillow:  pip install pillow")

DEFAULT_FRAME_RATE = 2


def png_to_xbm(path: Path) -> tuple[bytes, int, int]:
    """PNG -> (xbm_bytes, width, height). Dark, opaque pixels become set bits;
    bits are LSB-first within each byte, rows padded to whole bytes (u8g2 XBM)."""
    img = Image.open(path).convert("RGBA")
    w, h = img.size
    px = img.load()
    row_bytes = (w + 7) // 8
    out = bytearray(row_bytes * h)
    for y in range(h):
        for x in range(w):
            r, g, b, a = px[x, y]
            on = a >= 128 and (0.299 * r + 0.587 * g + 0.114 * b) < 128
            if on:
                out[y * row_bytes + (x >> 3)] |= 1 << (x & 7)
    return bytes(out), w, h


def frame_blob(xbm: bytes) -> bytes:
    """Uncompressed icon frame: a single is_compressed=0 flag byte + XBM data."""
    return b"\x00" + xbm


def build_static(png: Path, out_icon: Path) -> str:
    xbm, w, h = png_to_xbm(png)
    out_icon.parent.mkdir(parents=True, exist_ok=True)
    with open(out_icon, "wb") as f:
        f.write(struct.pack("<ii", w, h))  # StaticIconBmxHeader
        f.write(frame_blob(xbm))
    return f"static  {out_icon.name:32} {w}x{h}"


def build_animated(src_dir: Path, out_dir: Path, rate: int) -> str:
    frames = sorted(p for p in src_dir.glob("*.png"))
    if not frames:
        return f"SKIP    {src_dir.name}: no frame PNGs"
    meta_txt = src_dir / "meta.txt"
    if meta_txt.exists():
        for line in meta_txt.read_text().splitlines():
            if line.strip().startswith("frame_rate"):
                rate = int(line.split("=", 1)[1])
    out_dir.mkdir(parents=True, exist_ok=True)
    w = h = 0
    for i, png in enumerate(frames):
        xbm, w, h = png_to_xbm(png)
        with open(out_dir / f"frame_{i:02d}.bm", "wb") as f:
            f.write(frame_blob(xbm))
    with open(out_dir / "meta", "wb") as f:
        f.write(struct.pack("<iiii", w, h, rate, len(frames)))  # AnimatedIconMetaFile
    return f"animated {out_dir.name:31} {w}x{h} x{len(frames)} @ {rate}fps"


def main() -> int:
    ap = argparse.ArgumentParser(description="Build an applab asset pack from PNGs.")
    ap.add_argument("input", type=Path, help="input folder (Icons/ and Fonts/)")
    ap.add_argument("pack", help="pack name (the /asset_packs/<name> folder)")
    ap.add_argument("--out", type=Path, default=Path("build"), help="output root")
    ap.add_argument("--rate", type=int, default=DEFAULT_FRAME_RATE,
                    help="default animation frame rate (fps)")
    args = ap.parse_args()

    if not args.input.is_dir():
        return f"input not found: {args.input}"

    pack_root = args.out / args.pack
    icons_in = args.input / "Icons"
    made = 0

    if icons_in.is_dir():
        for entry in sorted(icons_in.iterdir()):
            if entry.is_file() and entry.suffix.lower() == ".png":
                print(build_static(entry, pack_root / "Icons" / (entry.stem + ".bmx")))
                made += 1
            elif entry.is_dir():
                print(build_animated(entry, pack_root / "Icons" / entry.name, args.rate))
                made += 1

    fonts_in = args.input / "Fonts"
    if fonts_in.is_dir():
        for u8f in sorted(fonts_in.glob("*.u8f")):
            dst = pack_root / "Fonts" / u8f.name
            dst.parent.mkdir(parents=True, exist_ok=True)
            dst.write_bytes(u8f.read_bytes())
            print(f"font    {u8f.name}")
            made += 1

    if not made:
        return "nothing built -- expected Icons/*.png, Icons/<name>/ folders, or Fonts/*.u8f"
    print(f"\nBuilt '{args.pack}' -> {pack_root}  ({made} assets)")
    print(f"Copy the '{args.pack}' folder to  /asset_packs/  on your microSD.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
